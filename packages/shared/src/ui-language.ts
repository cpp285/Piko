const reverse = new Map(Object.entries(UI_TRANSLATIONS).map(([english, chinese]) => [chinese, english]));
reverse.set("已完成", "Completed");
reverse.set("执行中", "Running");
reverse.set("待命", "Idle");
reverse.set("成员", "Agents");
const patterns = Object.entries(UI_TRANSLATIONS).filter(([key]) => key.includes("{{"))
  .sort(([a], [b]) => b.replace(/\{\{\d+\}\}/g, "").length - a.replace(/\{\{\d+\}\}/g, "").length);
const escape = (text: string) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

export function translateUI(text: string, language: UILanguage): string {
  const normalized = text.replace(/\s+/g, " ").trim();
  if (language === "zh" && UI_TRANSLATIONS[normalized]) return UI_TRANSLATIONS[normalized];
  if (language === "en" && reverse.has(normalized)) return reverse.get(normalized)!;
  for (const [english, chinese] of patterns) {
    const source = language === "zh" ? english : chinese;
    const target = language === "zh" ? chinese : english;
    const keys = [...source.matchAll(/\{\{(\d+)\}\}/g)].map(m => m[1]);
    const parts = source.split(/\{\{\d+\}\}/g);
    const match = normalized.match(new RegExp("^" + parts.map(escape).join("(.+?)") + "$"));
    if (match) {
      const values = new Map(keys.map((key, i) => [key, match[i + 1]]));
      return target.replace(/\{\{(\d+)\}\}/g, (_, key) => values.get(key) ?? "");
    }
  }
  return text;
}
